const names = new Map<string, string>();
for (const entry of vocabulary) {
  const [canonical, ...aliases] = entry.split("|");
  for (const name of [canonical!, ...aliases]) names.set(name.toLowerCase(), canonical!);
}
const alternatives = [...names.keys()]
  .sort((a, b) => b.length - a.length)
  .map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
  .join("|");
const skillPattern = new RegExp(`(?<![a-z0-9])(?:${alternatives})(?![a-z0-9])`, "gi");

export function listedSkills(text: string) {
  const matches = new Set<string>();
  for (const [word] of text.matchAll(skillPattern)) {
    // Short words like "go" in ordinary prose are ambiguous. Accept the technology spelling.
    if (word === "go" || (word.toLowerCase() === "rest" && word !== "REST")) continue;
    matches.add(names.get(word.toLowerCase())!);
  }
  return [...matches].sort();
}
export type ResumeMatch =
  | { status: "no-profile" | "no-requirements" }
  | { status: "scored"; matched: string[]; missing: string[]; total: number; percent: number };

export function resumeMatch(
  profile: ReadonlySet<string> | null,
  requirements: string,
): ResumeMatch {
  if (!profile?.size) return { status: "no-profile" };
  const skills = listedSkills(requirements);
  if (!skills.length) return { status: "no-requirements" };
  const matched = skills.filter((skill) => profile.has(skill));
  return {
    status: "scored",
    matched,
    missing: skills.filter((skill) => !profile.has(skill)),
    total: skills.length,
    percent: Math.round((100 * matched.length) / skills.length),
  };
}
