import { readFile, writeFile } from "node:fs/promises";
import { flows } from "../src/features/guidance/model/flows";
const file = new URL("../src/features/guidance/model/flow-catalog.generated.ts", import.meta.url);
const catalog = Object.values(flows).map(({ id, name, description }) => ({
  id,
  name,
  description,
}));
const source = `// Generated by npm run flows:catalog. Edit the full flow templates instead.\nimport type { FlowId } from "@/shared/contracts/database.generated";\nexport const flowCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly { id: FlowId; name: string; description: string }[];\nexport function isFlowId(value: string): value is FlowId { return flowCatalog.some(flow => flow.id === value); }\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(file, "utf8").catch(() => "")) !== source)
    throw new Error("Flow catalog is stale. Run npm run flows:catalog.");
  console.log("Flow catalog matches the full templates.");
} else await writeFile(file, source);
